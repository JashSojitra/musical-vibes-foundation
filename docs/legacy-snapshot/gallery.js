function insertGalleries() {
    const seniors = document.querySelector('.timeline');
    const music = document.querySelector('.timelinemusic');
    if (seniors) {
        galleryKeys = Object.keys(imageLists);
        timeline = document.querySelector('.timeline');
    }
    else if (music) {
        galleryKeys = Object.keys(musicList);
        timeline = document.querySelector('.timelinemusic');
       imageLists = musicList;
    }
    else {
        galleryKeys = Object.keys(o);
        timeline = document.querySelector('.timelineothers');
        imageLists = o;

    }



    timeline.innerHTML = '';
    galleryKeys.forEach((key, index) => {
        const group = document.createElement('div');
        group.className = 'group';
        group.innerHTML = `
            <div class="marker"></div>
            <h2 class="heading">${key}</h2>
            <div class="gallery-grid" data-gallery="${index}"></div>
        `;
        timeline.appendChild(group);
    });

    document.querySelectorAll('.gallery-grid').forEach((grid, index) => {
        const key = galleryKeys[index];

        if (!key || !imageLists[key]) return;

        let visibleCount = 5;

        function loadMedia() {
            grid.innerHTML = '';
            const itemsToShow = imageLists[key].slice(0, visibleCount);

            itemsToShow.forEach((src, mediaIndex) => {
                const div = document.createElement('div');
                div.className = 'gallery-item';

                if (src.match(/\.(mp4|webm|ogg)$/i)) {
                    const video = document.createElement('video');
                    video.src = src;
                    video.controls = true;
                    video.muted = true;
                    video.playsInline = true;
                    video.loading = 'lazy';
                    div.appendChild(video);
                } else {
                    const img = document.createElement('img');
                    img.src = src;
                    img.alt = `Image ${mediaIndex + 1}`;
                    img.loading = 'lazy';
                    div.appendChild(img);
                }

                if (mediaIndex === itemsToShow.length - 1 && visibleCount < imageLists[key].length) {
                    const overlay = document.createElement('div');
                    overlay.className = 'show-more-overlay';
                    overlay.textContent = 'Show More';
                    overlay.onclick = () => {
                        visibleCount += 5;
                        loadMedia();
                    };
                    div.appendChild(overlay);
                }

                grid.appendChild(div);
            });
        }

        loadMedia();
    });
}
// content loaded
document.addEventListener('DOMContentLoaded', () => {
    insertGalleries();
});
// zoom 
document.addEventListener('click', function (e) {
    const target = e.target;

    // Check if clicked element is image or video inside a gallery grid
    if (target.closest('.gallery-grid') && (target.tagName === 'IMG' || target.tagName === 'VIDEO')) {
        const modal = document.getElementById("imageModal");
        const modalContent = document.getElementById("modalContent");

        // Show modal
        modal.style.display = "flex";

        // Clear previous content
        modalContent.innerHTML = '';

        if (target.tagName === 'IMG') {
            const img = document.createElement('img');
            img.className = 'modal-content';
            img.src = target.src;
            img.alt = target.alt || '';
            modalContent.appendChild(img);
        } else if (target.tagName === 'VIDEO') {
            const video = document.createElement('video');
            video.className = 'modal-content';
            video.src = target.src;
            video.controls = true;
            video.autoplay = true;
            modalContent.appendChild(video);
        }
    }

    // Close modal when clicking on close button or outside modal content
    if (e.target.classList.contains("close") || e.target.id === "imageModal") {
        const modal = document.getElementById("imageModal");
        const modalContent = document.getElementById("modalContent");
        modal.style.display = "none";
        modalContent.innerHTML = ''; // clear modal content
    }
});
